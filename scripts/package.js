'use strict';
const fs=require('node:fs');
const path=require('node:path');
const {spawnSync}=require('node:child_process');
const root=path.join(__dirname,'..');
const version=require('../package.json').version;
const output=path.join(root,'release',`Super-Send-${version}-win32-x64`);
if(fs.existsSync(output))throw new Error('Release directory already exists. Move it before packaging a new build.');
const runtime=path.dirname(require('electron'));
fs.mkdirSync(output,{recursive:true});
fs.cpSync(runtime,output,{recursive:true});
const executable=path.join(output,'Super Send.exe');
fs.renameSync(path.join(output,'electron.exe'),executable);
const editor=process.env.RCEDIT_PATH||path.join(root,'tools','rcedit','rcedit-x64.exe');
if(!fs.existsSync(editor))throw new Error('Set RCEDIT_PATH to the official Electron rcedit v2.0.0 executable.');
const edited=spawnSync(editor,[executable,'--set-icon',path.join(root,'renderer','assets','super-send.ico'),'--set-version-string','ProductName','Super Send','--set-version-string','FileDescription','Super Send','--set-version-string','CompanyName','Super Send','--set-version-string','OriginalFilename','Super Send.exe','--set-file-version',version,'--set-product-version',version],{stdio:'inherit',windowsHide:true});
if(edited.error)throw edited.error;if(edited.status!==0)throw new Error('Windows branding resource update failed.');
const appRoot=path.join(output,'resources','app');
fs.mkdirSync(appRoot,{recursive:true});
for(const name of ['src','renderer','docs','scripts','package.json','README.md','LICENSE','THIRD_PARTY_NOTICES.md'])fs.cpSync(path.join(root,name),path.join(appRoot,name),{recursive:true});
fs.copyFileSync(path.join(root,'README.md'),path.join(output,'README.md'));
fs.mkdirSync(path.join(output,'received'),{recursive:true});
console.log(output);
